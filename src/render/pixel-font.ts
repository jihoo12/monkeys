export const PIXEL_GLYPH_WIDTH = 5;
export const PIXEL_GLYPH_HEIGHT = 7;
export const PIXEL_LETTER_SPACING = 1;

export function pixelTextPath(text: string): string {
  const normalized = normalize(text);
  let cursor = 0;
  let d = '';
  for (const char of normalized) {
    const glyph = GLYPHS[char] ?? GLYPHS['?'];
    if (!glyph) continue;
    for (let row = 0; row < PIXEL_GLYPH_HEIGHT; row += 1) {
      const line = glyph[row] ?? '00000';
      let runStart = -1;
      for (let col = 0; col <= PIXEL_GLYPH_WIDTH; col += 1) {
        const on = line[col] === '1';
        if (on && runStart < 0) runStart = col;
        if (!on && runStart >= 0) {
          const length = col - runStart;
          d += `M${cursor + runStart} ${row}h${length}v1h-${length}z`;
          runStart = -1;
        }
      }
    }
    cursor += PIXEL_GLYPH_WIDTH + PIXEL_LETTER_SPACING;
  }
  return d;
}

export function pixelTextWidth(text: string, scale: number): number {
  const length = normalize(text).length;
  if (length === 0) return 0;
  return (length * (PIXEL_GLYPH_WIDTH + PIXEL_LETTER_SPACING) - PIXEL_LETTER_SPACING) * scale;
}

export function pixelText(
  text: string,
  x: number,
  y: number,
  scale: number,
  fill: string,
  extra = '',
): string {
  const d = pixelTextPath(text);
  if (!d) return '';
  return `<path d="${d}" transform="translate(${x} ${y}) scale(${scale})" fill="${fill}" ${extra}/>`;
}

export function pixelTextShadow(
  text: string,
  x: number,
  y: number,
  scale: number,
  fill: string,
  shadowFill: string,
  offset = 2,
  extra = '',
): string {
  const shadow = pixelText(text, x + offset, y + offset, scale, shadowFill, extra);
  const foreground = pixelText(text, x, y, scale, fill, extra);
  return shadow + foreground;
}

export function truncatePixelText(text: string, maxWidth: number, scale: number): string {
  if (pixelTextWidth(text, scale) <= maxWidth) return text;
  const suffix = '...';
  let result = '';
  for (const char of normalize(text)) {
    const candidate = `${result}${char}`;
    if (pixelTextWidth(`${candidate}${suffix}`, scale) > maxWidth) break;
    result = candidate;
  }
  return `${result.trimEnd()}${suffix}`;
}

function normalize(text: string): string {
  return text
    .toUpperCase()
    .replace(/[^\x20-\x7E]/g, '?')
    .replace(/\s+/g, ' ');
}
